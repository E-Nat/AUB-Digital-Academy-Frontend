const { dbAsync, initSchema } = require('./db/database');
const { seedDatabase } = require('./db/seeds');

async function testUserManagementSuite() {
    console.log('====================================================');
    console.log('🧪 RUNNING USER MANAGEMENT TEST SUITE');
    console.log('====================================================\n');

    await initSchema();
    await seedDatabase();

    // 1. Test Fetch All Users
    const users = await dbAsync.all(`
        SELECT u.id, u.full_name, u.email, u.university_id, r.name as role
        FROM users u
        JOIN roles r ON u.role_id = r.id
    `);
    console.log(`✓ [1/8] Total Users in DB: ${users.length} (Expected >= 20)`);
    if (users.length < 20) throw new Error('Total users count lower than expected.');

    // 2. Test User Creation with Role & Academic Fields
    const newUserRes = await dbAsync.run(`
        INSERT INTO users (
            full_name, email, university_id, password_hash, role_id, status,
            phone, faculty, department_name, position, academic_year, semester, enrollment_status
        ) VALUES (
            'Jonathan Test Student', 'j.test.student@aub.edu.kh', '0009999', 'hash_pwd_123', 3, 'Active',
            '+855 23 999 999', 'Faculty of CS', 'Computer Science', 'Undergraduate', 'Year 3', 'Semester 1', 'Full-Time'
        )
    `);
    const createdUserId = newUserRes.lastID;
    console.log(`✓ [2/8] Create User: Successfully created Student with ID ${createdUserId}`);

    // 3. Test Activity Log Recording
    await dbAsync.run(`
        INSERT INTO user_activity_logs (user_id, action, details)
        VALUES (?, 'Account Created', 'Account created with role STUDENT')
    `, [createdUserId]);
    const logs = await dbAsync.all('SELECT * FROM user_activity_logs WHERE user_id = ?', [createdUserId]);
    console.log(`✓ [3/8] Activity Log: ${logs.length} activity logged for user`);

    // 4. Test Get User by ID (with Academic Details)
    const userDetail = await dbAsync.get(`
        SELECT u.*, r.name as role FROM users u JOIN roles r ON u.role_id = r.id WHERE u.id = ?
    `, [createdUserId]);
    if (userDetail.academic_year !== 'Year 3' || userDetail.phone !== '+855 23 999 999') {
        throw new Error('Academic details mismatch on created user');
    }
    console.log(`✓ [4/8] Get User By ID: Retrieved ${userDetail.full_name}, ${userDetail.role}, ${userDetail.academic_year}`);

    // 5. Test Update User Profile
    await dbAsync.run(`
        UPDATE users SET
            full_name = 'Jonathan Vance Student',
            academic_year = 'Year 4',
            semester = 'Semester 2',
            updated_at = CURRENT_TIMESTAMP
        WHERE id = ?
    `, [createdUserId]);
    const updatedUser = await dbAsync.get('SELECT full_name, academic_year, semester FROM users WHERE id = ?', [createdUserId]);
    if (updatedUser.academic_year !== 'Year 4' || updatedUser.semester !== 'Semester 2') {
        throw new Error('User update failed');
    }
    console.log(`✓ [5/8] Update User: Updated to ${updatedUser.full_name}, ${updatedUser.academic_year}`);

    // 6. Test Password Reset
    await dbAsync.run(`
        UPDATE users SET password_hash = 'new_bcrypt_hash_456', updated_at = CURRENT_TIMESTAMP WHERE id = ?
    `, [createdUserId]);
    await dbAsync.run(`
        INSERT INTO user_activity_logs (user_id, action, details)
        VALUES (?, 'Password Reset', 'Temporary password generated by administrator')
    `, [createdUserId]);
    const postResetLogs = await dbAsync.all('SELECT * FROM user_activity_logs WHERE user_id = ?', [createdUserId]);
    console.log(`✓ [6/8] Reset Password: Password updated and logged (${postResetLogs.length} total logs)`);

    // 7. Test Toggle Status (Suspend / Activate)
    await dbAsync.run(`UPDATE users SET status = 'Suspended', updated_at = CURRENT_TIMESTAMP WHERE id = ?`, [createdUserId]);
    const suspendedUser = await dbAsync.get('SELECT status FROM users WHERE id = ?', [createdUserId]);
    if (suspendedUser.status !== 'Suspended') throw new Error('Status toggle failed');
    console.log(`✓ [7/8] Toggle Status: User status successfully transitioned to ${suspendedUser.status}`);

    // 8. Test Delete User & Cascade cleanup
    await dbAsync.run('DELETE FROM user_activity_logs WHERE user_id = ?', [createdUserId]);
    await dbAsync.run('DELETE FROM users WHERE id = ?', [createdUserId]);
    const deletedUser = await dbAsync.get('SELECT id FROM users WHERE id = ?', [createdUserId]);
    if (deletedUser) throw new Error('Delete user failed');
    console.log('✓ [8/8] Delete User: Cleaned up test user successfully');

    console.log('\n====================================================');
    console.log('🎉 ALL 8 USER MANAGEMENT TEST CASES PASSED!');
    console.log('====================================================');
    process.exit(0);
}

testUserManagementSuite().catch(err => {
    console.error('Test failed:', err);
    process.exit(1);
});
