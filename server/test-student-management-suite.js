const { dbAsync, initSchema } = require('./db/database');
const { seedDatabase } = require('./db/seeds');

async function testStudentManagementSuite() {
    console.log('====================================================');
    console.log('🧪 RUNNING STUDENT MANAGEMENT TEST SUITE');
    console.log('====================================================\n');

    await initSchema();
    await seedDatabase();

    // 1. Fetch Students
    const students = await dbAsync.all(`
        SELECT u.*, r.name as role, p.title as major_title
        FROM users u
        JOIN roles r ON u.role_id = r.id
        LEFT JOIN programs p ON u.major_id = p.id
        WHERE r.name = 'STUDENT'
    `);
    console.log(`✓ [1/8] Total Students in DB: ${students.length} (Expected >= 5)`);
    if (students.length < 5) throw new Error('Total students count lower than expected.');

    // 2. Verify Sreyneang Sok Demo Record
    const sreyneang = students.find(s => s.university_id === '202401234');
    if (!sreyneang) throw new Error('Demo student Sreyneang Sok (202401234) not found.');
    console.log(`✓ [2/8] Verified Student: ${sreyneang.full_name}, ID: ${sreyneang.university_id}, Faculty: ${sreyneang.faculty}, Year: ${sreyneang.academic_year}, Enrollment: ${sreyneang.enrollment_status}`);

    // 3. Create Student (4-step wizard equivalent)
    const newStudentRes = await dbAsync.run(`
        INSERT INTO users (
            full_name, email, university_id, password_hash, role_id, major_id, status,
            phone, faculty, department_name, position, academic_year, semester,
            enrollment_status, academic_status, enrollment_date, expected_graduation_date,
            dob, gender, address, email_verified
        ) VALUES (
            'Vannak Chan', 'vannak.chan@aub.edu.kh', '202401239', 'hashed_pass_student_999', 3, 1, 'Active',
            '+855 12 999 101', 'Information Technology', 'Computer Science & IT', 'Undergraduate Student', 'Year 1', 'Semester 1',
            'Active', 'Currently Enrolled', '2024-09-01', '2028-07-15',
            '2005-03-22', 'Male', 'Phnom Penh, Cambodia', 1
        )
    `);
    const createdStudentId = newStudentRes.lastID;
    console.log(`✓ [3/8] Create Student: Created Vannak Chan (ID: 202401239, PK: ${createdStudentId})`);

    // 4. Update Student Academic Information
    await dbAsync.run(`
        UPDATE users SET
            academic_year = 'Year 2',
            semester = 'Semester 2',
            enrollment_status = 'Active',
            last_profile_update = CURRENT_TIMESTAMP
        WHERE id = ?
    `, [createdStudentId]);

    const updatedStudent = await dbAsync.get('SELECT academic_year, semester, enrollment_status FROM users WHERE id = ?', [createdStudentId]);
    if (updatedStudent.academic_year !== 'Year 2' || updatedStudent.semester !== 'Semester 2') {
        throw new Error('Student academic update failed.');
    }
    console.log(`✓ [4/8] Update Academic Details: Successfully promoted student to ${updatedStudent.academic_year} ${updatedStudent.semester}`);

    // 5. Test Filtering Query (Faculty & Year)
    const itYear2Students = await dbAsync.all(`
        SELECT u.id, u.full_name, u.university_id
        FROM users u
        WHERE u.role_id = 3 AND u.faculty = 'Information Technology' AND u.academic_year = 'Year 2'
    `);
    console.log(`✓ [5/8] Filter Query: Found ${itYear2Students.length} students in IT (Year 2)`);
    if (itYear2Students.length < 2) throw new Error('Filter query failed.');

    // 6. Test Activity Log Recording
    await dbAsync.run(`
        INSERT INTO user_activity_logs (user_id, action, details)
        VALUES (?, 'Academic Year Updated', 'Year 1 → Year 2')
    `, [createdStudentId]);
    const studentLogs = await dbAsync.all('SELECT * FROM user_activity_logs WHERE user_id = ?', [createdStudentId]);
    console.log(`✓ [6/8] Student Activity Log: ${studentLogs.length} audit entry recorded`);

    // 7. Test Student Password Reset
    await dbAsync.run(`
        UPDATE users SET password_hash = 'new_student_hashed_pw', updated_at = CURRENT_TIMESTAMP WHERE id = ?
    `, [createdStudentId]);
    await dbAsync.run(`
        INSERT INTO user_activity_logs (user_id, action, details)
        VALUES (?, 'Password Reset', 'Password reset generated by administrator')
    `, [createdStudentId]);
    console.log(`✓ [7/8] Password Reset: Secure password reset executed and audited`);

    // 8. Delete Student Account & Cleanup
    await dbAsync.run('DELETE FROM user_activity_logs WHERE user_id = ?', [createdStudentId]);
    await dbAsync.run('DELETE FROM users WHERE id = ?', [createdStudentId]);
    const deletedStudent = await dbAsync.get('SELECT id FROM users WHERE id = ?', [createdStudentId]);
    if (deletedStudent) throw new Error('Student deletion failed.');
    console.log(`✓ [8/8] Delete Student: Removed test student record safely`);

    console.log('\n====================================================');
    console.log('🎉 ALL 8 STUDENT MANAGEMENT TEST CASES PASSED!');
    console.log('====================================================');
    process.exit(0);
}

testStudentManagementSuite().catch(err => {
    console.error('Test failed:', err);
    process.exit(1);
});
